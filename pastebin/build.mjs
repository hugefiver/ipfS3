import { copyFile, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { deploymentDefaults } from "./config.js";
import { validateSettings } from "./settings.js";

const BYTES_PER_MIB = 1024 * 1024;
const SOURCE_DIR = path.dirname(fileURLToPath(import.meta.url));

export const RUNTIME_FILES = Object.freeze([
  "index.html",
  "styles.css",
  "app.js",
  "crypto.js",
  "publish.mjs",
  "settings.js",
  "share.js",
  "sigv4.mjs",
]);

function envText(env, name) {
  const value = env[name];
  if (typeof value !== "string") return undefined;
  const trimmed = value.trim();
  return trimmed ? trimmed : undefined;
}

export function resolveDeploymentDefaults(env = process.env, base = deploymentDefaults) {
  const bytesRaw = envText(env, "PASTEBIN_MAX_UPLOAD_BYTES");
  const mibRaw = envText(env, "PASTEBIN_MAX_UPLOAD_MIB");
  let maxUploadBytes = base.maxUploadBytes;
  if (bytesRaw !== undefined) {
    maxUploadBytes = Number(bytesRaw);
  } else if (mibRaw !== undefined) {
    const mib = Number(mibRaw);
    maxUploadBytes = Number.isFinite(mib) && mib > 0 ? Math.round(mib * BYTES_PER_MIB) : NaN;
  }

  return validateSettings({
    endpoint: envText(env, "PASTEBIN_ENDPOINT") ?? base.endpoint,
    bucket: envText(env, "PASTEBIN_BUCKET") ?? base.bucket,
    region: envText(env, "PASTEBIN_REGION") ?? base.region,
    maxUploadBytes,
    ipfsGateway: envText(env, "PASTEBIN_IPFS_GATEWAY") ?? base.ipfsGateway,
    inbrowserGateway: envText(env, "PASTEBIN_INBROWSER_GATEWAY") ?? base.inbrowserGateway,
  });
}

export function renderConfigModule(defaults) {
  return `// Generated by pastebin/build.mjs from deployment environment variables.\nexport const deploymentDefaults = Object.freeze(${JSON.stringify(defaults, null, 2)});\n`;
}

export async function buildSite(outDir, env = process.env) {
  const resolvedOut = path.resolve(outDir);
  if (resolvedOut === SOURCE_DIR) {
    throw new Error("Refusing to overwrite the pastebin source directory.");
  }
  const defaults = resolveDeploymentDefaults(env);
  await rm(resolvedOut, { recursive: true, force: true });
  await mkdir(resolvedOut, { recursive: true });
  for (const file of RUNTIME_FILES) {
    await copyFile(path.join(SOURCE_DIR, file), path.join(resolvedOut, file));
  }
  await writeFile(path.join(resolvedOut, "config.js"), renderConfigModule(defaults), "utf8");
  return defaults;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outDir = process.argv[2] || path.join(SOURCE_DIR, "dist");
  const defaults = await buildSite(outDir, process.env);
  console.log(`Built pastebin static site in ${path.resolve(outDir)} (endpoint=${defaults.endpoint}, bucket=${defaults.bucket}, maxUploadBytes=${defaults.maxUploadBytes})`);
}
